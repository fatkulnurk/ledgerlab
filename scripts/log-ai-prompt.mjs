#!/usr/bin/env node
/**
 * Log an AI interaction for the technical test.
 *
 * The test allows AI assistance, but every prompt that influenced the codebase
 * must be recorded. This script appends a structured record to
 * `docs/ai/prompt-log.jsonl` (the source of truth) and regenerates the
 * human-readable `docs/AI-PROMPT-LOG.md` table from it.
 *
 * Usage:
 *   pnpm ai:log -- \
 *     --tool "opencode" \
 *     --model "deepseek/deepseek-v4.1-flash" \
 *     --task "Implement double-entry validation" \
 *     --prompt "Add a check that debits equal credits on POST /journal-entries" \
 *     --summary "Added isBalanced check + 422 UnbalancedEntryError" \
 *     --files "apps/ledger-api/src/services/ledger-service.ts" \
 *     --decision "accepted" \
 *     --subagent "ledger-architect"
 *
 * Read the prompt from stdin with `--prompt -` (useful for pasting transcripts):
 *   pbpaste | pnpm ai:log -- --tool claude --task "..." --prompt -
 */
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const AI_DIR = join(ROOT, "docs", "ai");
const JSONL = join(AI_DIR, "prompt-log.jsonl");
const MARKDOWN = join(ROOT, "docs", "AI-PROMPT-LOG.md");

function parseArgs(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (!arg.startsWith("--")) continue;
    const key = arg.slice(2);
    const value = argv[i + 1];
    if (value === undefined || value.startsWith("--")) {
      out[key] = true;
    } else {
      out[key] = value;
      i += 1;
    }
  }
  return out;
}

async function readStdin() {
  const chunks = [];
  for await (const chunk of process.stdin) chunks.push(chunk);
  return Buffer.concat(chunks).toString("utf8").trim();
}

const args = parseArgs(process.argv.slice(2));

if (args.help) {
  console.log(
    readFileSync(fileURLToPath(import.meta.url), "utf8")
      .split("\n")
      .slice(1, 30)
      .join("\n"),
  );
  process.exit(0);
}

const prompt = args.prompt === true || args.prompt === "-" ? await readStdin() : args.prompt;
if (!prompt || typeof prompt !== "string") {
  console.error('Missing --prompt "…" (or --prompt - to read from stdin).');
  process.exit(1);
}

const record = {
  id: `ai_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 6)}`,
  timestamp: new Date().toISOString(),
  tool: typeof args.tool === "string" ? args.tool : "unknown",
  model: typeof args.model === "string" ? args.model : "unspecified",
  subagent: typeof args.subagent === "string" ? args.subagent : null,
  task: typeof args.task === "string" ? args.task : "untitled task",
  prompt,
  summary: typeof args.summary === "string" ? args.summary : "",
  decision: typeof args.decision === "string" ? args.decision : "accepted",
  files:
    typeof args.files === "string"
      ? args.files
          .split(",")
          .map((f) => f.trim())
          .filter(Boolean)
      : [],
};

mkdirSync(AI_DIR, { recursive: true });
appendFileSync(JSONL, `${JSON.stringify(record)}\n`, "utf8");

function escapePipes(text) {
  return String(text).replace(/\|/g, "\\|").replace(/\n+/g, " ").trim();
}

const lines = readFileSync(JSONL, "utf8")
  .split("\n")
  .filter(Boolean)
  .map((line) => JSON.parse(line));

const header = [
  "# AI Prompt Log",
  "",
  "> Generated by `pnpm ai:log`. Do not edit by hand — append via the script.",
  "",
  `Entries: **${lines.length}**`,
  "",
  "| # | Timestamp (UTC) | Tool / model | Sub-agent | Task | Prompt (truncated) | Decision | Files |",
  "|---|---|---|---|---|---|---|---|",
];

const rows = lines.map((entry, index) => {
  const promptPreview = escapePipes(entry.prompt).slice(0, 160) + (entry.prompt.length > 160 ? "…" : "");
  const files = entry.files.map((f) => `\`${f}\``).join("<br>") || "—";
  return `| ${index + 1} | ${entry.timestamp} | ${escapePipes(entry.tool)} / ${escapePipes(entry.model)} | ${
    entry.subagent ? `\`${entry.subagent}\`` : "—"
  } | ${escapePipes(entry.task)} | ${promptPreview} | ${escapePipes(entry.decision)} | ${files} |`;
});

writeFileSync(MARKDOWN, [...header, ...rows, ""].join("\n"), "utf8");
console.log(`Logged ${record.id}. ${lines.length} entries total.`);
if (!existsSync(JSONL)) console.warn("warning: jsonl not found");
